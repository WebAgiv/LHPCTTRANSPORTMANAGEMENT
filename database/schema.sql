CREATE DATABASE IF NOT EXISTS aitrc_transport_erp
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE aitrc_transport_erp;
SET FOREIGN_KEY_CHECKS = 0;

-- TABLE: users
CREATE TABLE IF NOT EXISTS users (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          ENUM('superadmin','principal','director','transport','finance','accountant','driver','security','student','parent') NOT NULL,
  full_name     VARCHAR(120) NOT NULL,
  email         VARCHAR(120),
  phone         VARCHAR(15),
  is_active     TINYINT(1) DEFAULT 1,
  last_login    DATETIME,
  created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_role(role)
) ENGINE=InnoDB;

-- TABLE: buses
CREATE TABLE IF NOT EXISTS buses (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  bus_number  VARCHAR(20) NOT NULL UNIQUE,
  capacity    SMALLINT NOT NULL DEFAULT 50,
  model       VARCHAR(80),
  is_active   TINYINT(1) DEFAULT 1,
  insurance_expiry DATE, fitness_expiry DATE, permit_expiry DATE,
  created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- TABLE: drivers
CREATE TABLE IF NOT EXISTS drivers (
  id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  driver_code    VARCHAR(10) NOT NULL UNIQUE,
  full_name      VARCHAR(120) NOT NULL,
  phone          VARCHAR(15) NOT NULL,
  license_no     VARCHAR(30) NOT NULL,
  license_expiry DATE,
  experience_yrs TINYINT DEFAULT 0,
  bus_id         INT UNSIGNED,
  user_id        INT UNSIGNED,
  status         ENUM('on-duty','leave','inactive') DEFAULT 'on-duty',
  created_at     DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bus_id) REFERENCES buses(id) ON DELETE SET NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- TABLE: routes
CREATE TABLE IF NOT EXISTS routes (
  id                  INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  route_name          VARCHAR(100) NOT NULL,
  end_point           VARCHAR(80) NOT NULL,
  bus_id              INT UNSIGNED,
  driver_id           INT UNSIGNED,
  capacity            SMALLINT DEFAULT 50,
  morning_departure   TIME,
  evening_departure   TIME DEFAULT '17:30:00',
  annual_fare_typical INT UNSIGNED DEFAULT 8000 COMMENT 'ACOP typical annual fare INR',
  monthly_fare        INT UNSIGNED,
  is_active           TINYINT(1) DEFAULT 1,
  created_at          DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bus_id) REFERENCES buses(id) ON DELETE SET NULL,
  FOREIGN KEY (driver_id) REFERENCES drivers(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- TABLE: stops (340 real stops from PDF)
CREATE TABLE IF NOT EXISTS stops (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  route_id    INT UNSIGNED NOT NULL,
  stop_order  TINYINT NOT NULL,
  stop_name   VARCHAR(150) NOT NULL,
  acop_fare   INT UNSIGNED DEFAULT 0 COMMENT 'Annual ACOP fare INR',
  monthly_fare INT UNSIGNED DEFAULT 0,
  payment_plan ENUM('single','two') GENERATED ALWAYS AS (CASE WHEN acop_fare<=10000 AND acop_fare>0 THEN 'single' ELSE 'two' END) STORED,
  arrival_time TIME,
  created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (route_id) REFERENCES routes(id) ON DELETE CASCADE,
  INDEX idx_route_stop(route_id, stop_order)
) ENGINE=InnoDB;

-- TABLE: students
CREATE TABLE IF NOT EXISTS students (
  id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  student_code    VARCHAR(20) NOT NULL UNIQUE,
  user_id         INT UNSIGNED,
  full_name       VARCHAR(120) NOT NULL,
  email           VARCHAR(120),
  phone           VARCHAR(15),
  parent_phone    VARCHAR(15),
  gender          ENUM('Male','Female','Other'),
  dob             DATE,
  branch          ENUM('Computer Engineering','Mechanical Engineering','Civil Engineering','Electronics & Telecom','Information Technology','Electrical Engineering','Other'),
  year            TINYINT,
  division        VARCHAR(4),
  roll_no         VARCHAR(20),
  admission_type  ENUM('Regular','Direct Second Year (DSY)','Lateral Entry') DEFAULT 'Regular',
  route_id        INT UNSIGNED,
  stop_id         INT UNSIGNED,
  pass_status     ENUM('active','pending','expired','suspended') DEFAULT 'pending',
  pass_valid_from DATE,
  pass_valid_to   DATE,
  photo_url       VARCHAR(255),
  created_at      DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id)  REFERENCES users(id)    ON DELETE SET NULL,
  FOREIGN KEY (route_id) REFERENCES routes(id)   ON DELETE SET NULL,
  FOREIGN KEY (stop_id)  REFERENCES stops(id)    ON DELETE SET NULL,
  INDEX idx_code(student_code), INDEX idx_status(pass_status), INDEX idx_route(route_id)
) ENGINE=InnoDB;

-- TABLE: payments (smart 2-installment aware)
CREATE TABLE IF NOT EXISTS payments (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  payment_ref     VARCHAR(40) NOT NULL UNIQUE,
  student_id      INT UNSIGNED NOT NULL,
  route_id        INT UNSIGNED,
  amount          INT UNSIGNED NOT NULL,
  annual_fare     INT UNSIGNED COMMENT 'Full annual ACOP fare for this stop',
  payment_plan    ENUM('single','two') DEFAULT 'two',
  installment_no  TINYINT DEFAULT 1,
  installment_of  TINYINT DEFAULT 1,
  for_period_from DATE,
  for_period_to   DATE,
  academic_year   VARCHAR(10) DEFAULT '2025-26',
  method          ENUM('upi','card','netbanking','cash') DEFAULT 'upi',
  gateway_txn_id  VARCHAR(100),
  status          ENUM('pending','success','failed','refunded') DEFAULT 'pending',
  payment_date    DATETIME DEFAULT CURRENT_TIMESTAMP,
  collected_by    INT UNSIGNED,
  notes           TEXT,
  FOREIGN KEY (student_id)   REFERENCES students(id),
  FOREIGN KEY (route_id)     REFERENCES routes(id)   ON DELETE SET NULL,
  FOREIGN KEY (collected_by) REFERENCES users(id)    ON DELETE SET NULL,
  INDEX idx_student(student_id), INDEX idx_status(status), INDEX idx_plan(payment_plan, installment_no)
) ENGINE=InnoDB;

-- TABLE: notices
CREATE TABLE IF NOT EXISTS notices (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  notice_code VARCHAR(15) NOT NULL UNIQUE,
  title       VARCHAR(200) NOT NULL,
  category    VARCHAR(60) DEFAULT 'General Announcement',
  body        TEXT NOT NULL,
  urgency     ENUM('high','medium','low') DEFAULT 'medium',
  target      VARCHAR(80) DEFAULT 'All Students',
  route_id    INT UNSIGNED,
  channels    JSON,
  pinned      TINYINT(1) DEFAULT 0,
  is_active   TINYINT(1) DEFAULT 1,
  expiry_date DATE,
  created_by  INT UNSIGNED,
  created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (route_id)   REFERENCES routes(id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES users(id)  ON DELETE SET NULL,
  INDEX idx_active(is_active), INDEX idx_urgency(urgency)
) ENGINE=InnoDB;

-- TABLE: notice_reads
CREATE TABLE IF NOT EXISTS notice_reads (
  id        BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  notice_id INT UNSIGNED NOT NULL,
  user_id   INT UNSIGNED NOT NULL,
  read_at   DATETIME DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq(notice_id, user_id),
  FOREIGN KEY (notice_id) REFERENCES notices(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id)   REFERENCES users(id)   ON DELETE CASCADE
) ENGINE=InnoDB;

-- TABLE: expenses
CREATE TABLE IF NOT EXISTS expenses (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  expense_code  VARCHAR(15) NOT NULL UNIQUE,
  bus_id        INT UNSIGNED,
  driver_id     INT UNSIGNED,
  expense_type  ENUM('fuel','maintenance','toll','allowance','insurance','permit','other') DEFAULT 'fuel',
  amount        INT UNSIGNED NOT NULL,
  expense_date  DATE NOT NULL,
  description   VARCHAR(255),
  document_path VARCHAR(255),
  litres        DECIMAL(6,2),
  status        ENUM('pending','approved','rejected') DEFAULT 'pending',
  approved_by   INT UNSIGNED,
  approved_at   DATETIME,
  submitted_by  INT UNSIGNED,
  created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bus_id)       REFERENCES buses(id)   ON DELETE SET NULL,
  FOREIGN KEY (driver_id)    REFERENCES drivers(id) ON DELETE SET NULL,
  FOREIGN KEY (approved_by)  REFERENCES users(id)   ON DELETE SET NULL,
  FOREIGN KEY (submitted_by) REFERENCES users(id)   ON DELETE SET NULL,
  INDEX idx_type(expense_type), INDEX idx_status(status), INDEX idx_date(expense_date)
) ENGINE=InnoDB;

-- TABLE: security_logs
CREATE TABLE IF NOT EXISTS security_logs (
  id         BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  student_id INT UNSIGNED,
  scanned_by INT UNSIGNED,
  scan_time  DATETIME DEFAULT CURRENT_TIMESTAMP,
  action     ENUM('entry','exit') DEFAULT 'entry',
  result     ENUM('valid','invalid','expired','suspended') DEFAULT 'valid',
  qr_data    VARCHAR(500),
  ip_address VARCHAR(45),
  FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE SET NULL,
  FOREIGN KEY (scanned_by) REFERENCES users(id)    ON DELETE SET NULL,
  INDEX idx_time(scan_time), INDEX idx_result(result)
) ENGINE=InnoDB;

-- TABLE: activity_log
CREATE TABLE IF NOT EXISTS activity_log (
  id         BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  type       ENUM('registration','payment','notice','alert','driver','security','system','login','bulk_upload') DEFAULT 'system',
  title      VARCHAR(200) NOT NULL,
  body       TEXT,
  user_id    INT UNSIGNED,
  related_id VARCHAR(40),
  is_read    TINYINT(1) DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_type(type), INDEX idx_read(is_read), INDEX idx_created(created_at)
) ENGINE=InnoDB;

-- TABLE: sessions
CREATE TABLE IF NOT EXISTS sessions (
  id            BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id       INT UNSIGNED NOT NULL,
  refresh_token VARCHAR(512) NOT NULL,
  ip_address    VARCHAR(45),
  expires_at    DATETIME NOT NULL,
  created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_token(refresh_token(64)), INDEX idx_user(user_id)
) ENGINE=InnoDB;

-- TABLE: fare_matrix (quick lookup by village)
CREATE TABLE IF NOT EXISTS fare_matrix (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  village     VARCHAR(100) NOT NULL,
  annual_fare INT UNSIGNED NOT NULL,
  monthly_fare INT UNSIGNED NOT NULL,
  route_id    INT UNSIGNED,
  payment_plan ENUM('single','two') GENERATED ALWAYS AS (CASE WHEN annual_fare<=10000 THEN 'single' ELSE 'two' END) STORED,
  inst1       INT UNSIGNED GENERATED ALWAYS AS (CASE WHEN annual_fare>10000 THEN CEIL(annual_fare/2) ELSE annual_fare END) STORED,
  inst2       INT UNSIGNED GENERATED ALWAYS AS (CASE WHEN annual_fare>10000 THEN annual_fare-CEIL(annual_fare/2) ELSE 0 END) STORED,
  created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (route_id) REFERENCES routes(id) ON DELETE SET NULL,
  INDEX idx_village(village)
) ENGINE=InnoDB;

SET FOREIGN_KEY_CHECKS = 1;

